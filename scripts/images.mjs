// ---------------------------------------------------------------------------
// Shimmer image pipeline
//
// Reads the photography in src/assets/images and emits responsive AVIF, WebP
// and JPEG derivatives into public/media, plus a generated manifest consumed
// by <Picture>. Also builds the social sharing image at public/og-image.jpg.
//
// Top-level files keep their file name as the logical key. Product photography
// in src/assets/images/Products/1.png … 21.png becomes product-1 … product-21,
// matching the catalogue data.
//
//   npm run images
// ---------------------------------------------------------------------------
import { mkdir, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import sharp from 'sharp'

const root = process.cwd()
const sourceDir = path.join(root, 'src', 'assets', 'images')
const productsDir = path.join(sourceDir, 'Products')
const outputDir = path.join(root, 'public', 'media')
const manifestPath = path.join(
  root,
  'src',
  'data',
  'generated',
  'imageManifest.js',
)
const OG_PATH = path.join(root, 'public', 'og-image.jpg')

const WIDTHS = [480, 960, 1600]
const QUALITY = { avif: 52, webp: 74, jpeg: 80 }
const supported = /\.(jpe?g|png)$/i

async function exists(file) {
  try {
    const stat = await sharp(file).metadata()
    return stat
  } catch {
    return null
  }
}

async function listImages(directory, prefix = '') {
  let entries = []
  try {
    entries = await readdir(directory, { withFileTypes: true })
  } catch {
    return []
  }

  return entries
    .filter((entry) => entry.isFile() && supported.test(entry.name))
    .map((entry) => ({
      file: path.join(directory, entry.name),
      key: `${prefix}${entry.name.replace(supported, '')}`,
    }))
}

async function main() {
  await mkdir(outputDir, { recursive: true })
  await mkdir(path.dirname(manifestPath), { recursive: true })

  const sources = [
    ...(await listImages(sourceDir)),
    ...(await listImages(productsDir, 'product-')),
  ].sort((a, b) => a.key.localeCompare(b.key, 'en', { numeric: true }))

  if (!sources.length) {
    throw new Error(`No source images found in ${sourceDir}`)
  }

  const manifest = {}
  const seen = new Set()

  for (const { file, key } of sources) {
    if (seen.has(key)) {
      throw new Error(`Duplicate image key "${key}" in ${sourceDir}`)
    }
    seen.add(key)

    const meta = await sharp(file).metadata()

    const targetWidths = [
      ...new Set([...WIDTHS.filter((width) => width < meta.width), meta.width]),
    ]

    const srcSet = { avif: [], webp: [], jpg: [] }

    for (const width of targetWidths) {
      const base = `${key}-${width}`
      for (const format of ['avif', 'webp', 'jpeg']) {
        await sharp(file)
          .resize({ width, withoutEnlargement: true })
          .toFormat(format, { quality: QUALITY[format] })
          .toFile(
            path.join(
              outputDir,
              `${base}.${format === 'jpeg' ? 'jpg' : format}`,
            ),
          )
      }
      srcSet.avif.push(`/media/${base}.avif ${width}w`)
      srcSet.webp.push(`/media/${base}.webp ${width}w`)
      srcSet.jpg.push(`/media/${base}.jpg ${width}w`)
    }

    const fallbackWidth =
      targetWidths.find((width) => width >= 960) || targetWidths.at(-1)
    const aspect = meta.height / meta.width

    manifest[key] = {
      width: fallbackWidth,
      height: Math.round(fallbackWidth * aspect),
      src: `/media/${key}-${fallbackWidth}.jpg`,
      sources: {
        avif: srcSet.avif.join(', '),
        webp: srcSet.webp.join(', '),
        jpg: srcSet.jpg.join(', '),
      },
    }
  }

  const body = `// Generated by scripts/images.mjs — do not edit by hand.\n// Run \`npm run images\` after changing any source photography.\nexport const imageManifest = ${JSON.stringify(
    manifest,
    null,
    2,
  )}\n`
  await writeFile(manifestPath, body, 'utf8')

  // Social card — crop the campaign hero to the 1200×630 OG ratio.
  const hero = await exists(path.join(sourceDir, 'hero.jpg'))
  if (hero) {
    await sharp(path.join(sourceDir, 'hero.jpg'))
      .resize(1200, 630, { fit: 'cover', position: 'attention' })
      .jpeg({ quality: 82, mozjpeg: true })
      .toFile(OG_PATH)
  }

  console.log(
    `images: ${sources.length} sources → ${Object.keys(manifest).length} manifest entries`,
  )
}

main().catch((error) => {
  console.error('images: failed —', error.message)
  process.exitCode = 1
})
